import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {copyFileSync,mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {validateEditableHtmlContract,validatePresentationHtmlContract} from '../integrations/nbskill/scripts/manifest-lib.mjs';
const root=mkdtempSync(join(tmpdir(),'nbskill-presentation-default-'));
for (const name of ['presentation.html','presentation-mark.svg']) copyFileSync(resolve('integrations/nbskill/templates',name),join(root,name));
const source=readFileSync(join(root,'presentation.html'),'utf8');
validateEditableHtmlContract(source);
validatePresentationHtmlContract(source);
const extractPptx=readFileSync(resolve('src-tauri/src/core/thumbnail/html_pptx_extract.js'),'utf8');
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[],remote=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route(/^https?:/,route=>{remote.push(route.request().url());return route.abort()});
 await page.goto(pathToFileURL(join(root,'presentation.html')).href);
 await page.waitForFunction(()=>Boolean(window.__NUTBOOK_MOTION__));
 assert.equal(await page.locator('[data-prev],[data-next],nav button').count(),0,'no inherited floating paging buttons');
 assert.ok(await page.evaluate(()=>__NUTBOOK_MOTION__.getConfig().pages.every(p=>!p.actions.length&&p.background===null&&p.transition===null)));
 assert.equal(await page.evaluate(()=>__NUTBOOK_MOTION__.state().playing),false);
 const counter=page.locator('[data-page-count]');
 assert.equal(await counter.getAttribute('data-page-count'),'1 / 3');
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'evidence');
 assert.equal(await counter.getAttribute('data-page-count'),'2 / 3');
 const chart=page.locator('[data-nutbook-chart]');
 assert.equal(await chart.isVisible(),true);
 assert.deepEqual(await chart.locator('[data-label]').evaluateAll(bars=>bars.map(bar=>bar.dataset.label)),['一季度','二季度','三季度']);
 const exported=await page.evaluate(`(${extractPptx})('evidence',innerWidth,innerHeight,0,0)`);
 assert.equal(exported.charts.length,1);
 assert.equal(exported.charts[0].kind,'bar');
 assert.deepEqual(exported.charts[0].series,[{name:'订单',values:[12,18,24]}]);
 assert.ok(exported.texts.some(text=>text.name==='evidence-title'),'the slide heading exports separately as editable text');
 await page.keyboard.press('Space');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'finish');
 await page.keyboard.press('PageUp');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'evidence');
 await page.evaluate(()=>__NUTBOOK_PRESENTATION__.setManagedMode(true));
 assert.equal(await counter.isVisible(),false);
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'evidence');
 await page.evaluate(()=>{__NUTBOOK_PRESENTATION__.setManagedMode(false);__NUTBOOK_PRESENTATION__.setEditMode(true)});
 assert.equal(await counter.isVisible(),false);
 await page.keyboard.press('PageDown');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'evidence');
 await page.evaluate(()=>__NUTBOOK_PRESENTATION__.setEditMode(false));
 assert.equal(await counter.isVisible(),true);
 await page.evaluate(()=>{const input=document.createElement('input');document.body.append(input);input.focus()});
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'evidence','typing focus does not navigate');
 await page.evaluate(()=>{document.querySelector('input').remove();dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',isComposing:true,bubbles:true}))});
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'evidence','IME does not navigate');
 await page.keyboard.press('PageDown');
 assert.equal(await page.evaluate(()=>__NUTBOOK_PRESENTATION__.activePageId),'finish');
 assert.ok(await page.locator('img').evaluate(img=>img.complete&&img.naturalWidth>0));
 assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
 console.log('Default nbskill deck: empty motion support, keyboard-only paging, page count, managed/edit/focus/IME guards passed');
} finally {await browser.close();rmSync(root,{recursive:true,force:true})}
