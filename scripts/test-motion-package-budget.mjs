import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,copyFileSync,mkdtempSync,unlinkSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {auditMotionArtifacts} from './audit-motion-package.mjs';
const dir=mkdtempSync(join(tmpdir(),'nutbook-motion-budget-')),file=join(dir,'index.html');
const source=readFileSync('integrations/nbskill/templates/motion-presentation.html','utf8');
writeFileSync(file,source);copyFileSync('integrations/nbskill/templates/presentation-mark.svg',join(dir,'presentation-mark.svg'));
const good=auditMotionArtifacts(dir,['index.html']);assert.ok(good.totalBytes<10*1024*1024);
writeFileSync(file,source.replace('./presentation-mark.svg','https://example.invalid/image.svg'));
assert.throws(()=>auditMotionArtifacts(dir,['index.html']),/non-portable resource/);
writeFileSync(file,source+'x'.repeat(3*1024*1024));assert.throws(()=>auditMotionArtifacts(dir,['index.html']),/HTML exceeds/);
writeFileSync(file,source.replace('window.__NUTBOOK_MOTION__','/*'+'x'.repeat(2*1024*1024)+'*/window.__NUTBOOK_MOTION__'));
assert.throws(()=>auditMotionArtifacts(dir,['index.html']),/runtime exceeds/);
writeFileSync(file,source);unlinkSync(join(dir,'presentation-mark.svg'));assert.throws(()=>auditMotionArtifacts(dir,['index.html']),/ENOENT/);
copyFileSync('integrations/nbskill/templates/presentation-mark.svg',join(dir,'presentation-mark.svg'));
const files=Array.from({length:5},(_,i)=>`large-${i}.html`);for(const name of files)writeFileSync(join(dir,name),source+'<!--'+'x'.repeat(2200000)+'-->');
assert.throws(()=>auditMotionArtifacts(dir,files),/package exceeds/);
console.log('Motion package audit rejects missing/remote resources and runtime/HTML/package budget overruns');
