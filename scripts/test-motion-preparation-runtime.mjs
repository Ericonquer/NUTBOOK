import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdtempSync,copyFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const dir=mkdtempSync(join(tmpdir(),'nutbook-motion-preparation-')),file=join(dir,'index.html');
copyFileSync('integrations/nbskill/templates/motion-presentation.html',file);
copyFileSync('integrations/nbskill/templates/presentation-mark.svg',join(dir,'presentation-mark.svg'));
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:2}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));await page.route(/^https?:/,route=>route.abort());
 await page.goto(pathToFileURL(file).href);
 await page.evaluate(()=>window.__TAURI_INTERNALS__={invoke:async()=>true});
 await page.addScriptTag({path:resolve('dist/assets/html-edit-runtime.js')});
 await page.evaluate(()=>window.__NUTBOOK_HTML_EDIT__.enter({itemId:1,runtimeSessionId:'preparation-test',generation:1,inlineToolbar:true,locale:'zh-CN'}));await page.evaluate(()=>window.__NUTBOOK_MOTION__.togglePanel());
 const hold=()=>page.evaluate(()=>{window.releaseMotionFonts=null;const promise=new Promise(resolve=>window.releaseMotionFonts=resolve);Object.defineProperty(document.fonts,'ready',{configurable:true,value:promise});});
 const release=()=>page.evaluate(()=>{window.releaseMotionFonts();delete document.fonts.ready;});
 await hold();await page.locator('[data-nutbook-motion-panel]').locator('[data-apply]').click();
 const recovery=page.locator('[data-nutbook-motion-panel]').locator('[data-motion-feedback]');
 await recovery.locator('p').filter({hasText:'正在准备动画'}).waitFor();
 await recovery.locator('[data-cancel]').click();
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().preparing),false);
 await release();await page.waitForTimeout(50);
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().playing),false);
 assert.equal(await page.locator('[data-id="opening-title"]').evaluate(el=>getComputedStyle(el).opacity),'1');
 const saved=await page.evaluate(()=>JSON.stringify(window.__NUTBOOK_HTML_EDIT__.getSnapshot().changes));
 await hold();await page.evaluate(()=>{void window.__NUTBOOK_MOTION__.replay();});
 await recovery.locator('p').filter({hasText:'动画准备时间过长'}).waitFor({timeout:3500});
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().preparing),false);
 await recovery.locator('[data-low]').click();await release();
 await page.waitForFunction(()=>window.__NUTBOOK_MOTION__.state().playing);
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().renderMode),'low');
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.canvas.width),1280);
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.getConfig().pages[0].actions[0].params.density),180);
 assert.equal(await recovery.isVisible(),false,'successful retry has no persistent popup');
 assert.equal(await page.evaluate(()=>JSON.stringify(window.__NUTBOOK_HTML_EDIT__.getSnapshot().changes)),saved,'fallback does not alter saved parameters');
 await page.locator('[data-nutbook-motion-panel]').locator('[data-replay]').click();await page.waitForFunction(()=>window.__NUTBOOK_MOTION__.state().playing);
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.canvas.width),2560);
 await hold();await page.evaluate(()=>{void window.__NUTBOOK_MOTION__.replay();Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
 await release();assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().preparing),false);
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().playing),false);
 await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
 await page.waitForFunction(()=>window.__NUTBOOK_MOTION__.state().preview);
 await hold();await page.evaluate(()=>{void window.__NUTBOOK_MOTION__.replay();});
 await recovery.locator('p').filter({hasText:'动画准备时间过长'}).waitFor({timeout:3500});
 await recovery.locator('[data-static]').click();await release();
 assert.equal(await page.evaluate(()=>window.__NUTBOOK_MOTION__.state().playing),false);
 assert.equal(await page.locator('[data-id="opening-title"]').evaluate(el=>getComputedStyle(el).opacity),'1');
 assert.equal(await page.locator('[data-nutbook-motion-recovery]').count(),0,'editor feedback stays inside motion panel');
 await page.evaluate(()=>window.__NUTBOOK_MOTION__.dispose());assert.equal(await recovery.count(),0);assert.deepEqual(errors,[]);
 console.log(`Preparation progress/cancel/timeout/low/static/standard and parameter preservation passed: ${dir}`);
}finally{await browser.close();}
