import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {readFileSync,writeFileSync,mkdtempSync,copyFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const dir=mkdtempSync(join(tmpdir(),'nutbook-motion-preview-')),file=join(dir,'index.html');
const base=readFileSync('integrations/nbskill/templates/motion-presentation.html','utf8');
const marker='<script type="application/json" id="nutbook-motion-config" data-id="nutbook-motion-config">';
const start=base.indexOf(marker)+marker.length,end=base.indexOf('</script>',start),config=JSON.parse(base.slice(start,end));
config.pages[0].actions=[{id:'preview-probe',targetId:config.pages[0].targets.find(t=>t.kind==='text').id,templateId:'text.glyph-particles',templateVersion:1,params:{durationMs:1800,strength:1,density:180,hue:210},seed:42,trigger:'click',delayMs:0}];
const source=base.slice(0,start)+JSON.stringify(config)+base.slice(end);writeFileSync(file,source);
copyFileSync('integrations/nbskill/templates/presentation-mark.svg',join(dir,'presentation-mark.svg'));
const trace={sourceHash:createHash('sha256').update(source).digest('hex'),events:[]};
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1280,height:720},reducedMotion:'no-preference'});
 await page.route(/^https?:/,route=>route.abort());
 const record=async action=>{const state=await page.evaluate(()=>({page:window.__NUTBOOK_PRESENTATION__.activePageId,...window.__NUTBOOK_MOTION__.state(),actions:window.__NUTBOOK_MOTION__.getConfig().pages[0].actions}));trace.events.push({action,...state});return state;};
 await page.goto(pathToFileURL(file).href);
 await page.waitForFunction(()=>window.__NUTBOOK_MOTION__);
 const opened=await record('open saved document');
 await page.evaluate(()=>window.__TAURI_INTERNALS__={invoke:async()=>true});
 await page.addScriptTag({path:resolve('dist/assets/html-edit-runtime.js')});
 await page.evaluate(()=>window.__NUTBOOK_HTML_EDIT__.enter({itemId:1,runtimeSessionId:'preview-test',generation:1,inlineToolbar:true,locale:'zh-CN'}));await page.evaluate(()=>window.__NUTBOOK_MOTION__.togglePanel());
 const controls=page.locator('[data-nutbook-motion-panel]');
 for(const param of ['durationMs','strength','density','hue'])assert.equal(await controls.locator(`[data-param="${param}"]`).isEnabled(),true,'reopen selects the object with saved motion');
 const target=await page.evaluate(()=>window.__NUTBOOK_MOTION__.getConfig().pages[0].actions[0].targetId);
 await page.locator(`[data-id="${target}"]`).click();
 await page.evaluate(()=>window.__NUTBOOK_MOTION__.seek(700));
 const before=await record('paused at 700ms');
 const canvasBefore=await page.evaluate(()=>window.__NUTBOOK_MOTION__.canvas.toDataURL());
 await page.locator('[data-nutbook-motion-panel]').locator('[data-param="density"]').evaluate(input=>{input.value=input.value==='400'?'12':'400';input.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.waitForFunction(()=>window.__NUTBOOK_MOTION__.state().scheduledFrames===0);
 const during=await record('density input held');
 const canvasAfter=await page.evaluate(()=>window.__NUTBOOK_MOTION__.canvas.toDataURL());
 await page.locator('[data-nutbook-motion-panel]').locator('[data-param="density"]').dispatchEvent('change');
 await page.waitForFunction(()=>window.__NUTBOOK_MOTION__.state().scheduledFrames===0);
 const committed=await record('density change committed');
 assert.equal(opened.playing,true,'saved document must begin playback on open');
 assert.equal(during.playing,false,'parameter input must not restart animation');
 assert.equal(during.logicalTimeMs,before.logicalTimeMs,'density keeps the paused preview time');
 assert.notEqual(canvasAfter,canvasBefore,'density changes visible particle state');
 assert.equal(committed.logicalTimeMs,before.logicalTimeMs,'committing slider preserves preview time');
 assert.equal(committed.preview,true,'committing slider preserves visible preview');
 console.log(`Motion preview behavior passed: ${dir}`);
}finally{writeFileSync(join(dir,'trace.json'),JSON.stringify(trace,null,2));console.log(`Motion behavior trace: ${dir}/trace.json`);await browser.close();}
